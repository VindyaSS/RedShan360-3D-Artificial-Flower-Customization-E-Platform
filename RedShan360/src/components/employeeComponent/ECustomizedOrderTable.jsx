import React, { useEffect, useMemo, useState } from 'react';
import { jsPDF } from 'jspdf';
import {
    Check,
    Play,
    Pause,
    AlertCircle,
    Inbox,
    ChevronDown,
    ChevronUp
} from 'lucide-react';

import EStartButton from './EStartButton';
import EStopButton from './EStopButton';
import ECompletedButton from './ECompletedButton';

import '../../css/employee.css';

//------------------ CUSTOMIZED ORDER TABLE -------------------------------------
export default function ECustomizedOrderTable({
    orders,
    orderItems,
    onStart,
    onStop,
    onResume,
    onComplete,
    onItemClick
}) {
    //------------------ BACKEND DATA -----------------------------------------------
    const displayOrders = Array.isArray(orders) ? orders : [];

    //------------------ EXPORT AS PDF ---------------------------------------------
    const handleExportPdf = async (item, orderId) => {
        const imageFullUrl = `http://localhost:8080${item.imageUrl}`;

        // Load the image as base64 via canvas
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.src = imageFullUrl;

        img.onload = () => {
            const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

            // --- Header ---
            pdf.setFillColor(116, 79, 81); // #744F51 brand colour
            pdf.rect(0, 0, 210, 28, 'F');
            pdf.setTextColor(255, 255, 255);
            pdf.setFontSize(16);
            pdf.setFont('helvetica', 'bold');
            pdf.text('Customized Bouquet Reference', 15, 12);
            pdf.setFontSize(10);
            pdf.setFont('helvetica', 'normal');
            pdf.text(`Order #RS-000${orderId}  |  Custom Item ID: ${item.itemId}`, 15, 20);

            // --- Bouquet image ---
            const canvas = document.createElement('canvas');
            canvas.width = img.naturalWidth;
            canvas.height = img.naturalHeight;
            const ctx = canvas.getContext('2d');
            ctx.drawImage(img, 0, 0);
            const dataUrl = canvas.toDataURL('image/png');

            // Centre image, max 130×130 mm
            const maxW = 130;
            const maxH = 130;
            const ratio = Math.min(maxW / img.naturalWidth, maxH / img.naturalHeight);
            const imgW = img.naturalWidth * ratio;
            const imgH = img.naturalHeight * ratio;
            const imgX = (210 - imgW) / 2;
            pdf.addImage(dataUrl, 'PNG', imgX, 36, imgW, imgH);

            // --- Details section ---
            const detailsY = 36 + imgH + 10;
            pdf.setDrawColor(229, 216, 216);
            pdf.line(15, detailsY, 195, detailsY);

            pdf.setTextColor(40, 40, 40);
            pdf.setFontSize(11);
            pdf.setFont('helvetica', 'bold');
            pdf.text('Bouquet Order ID: #RS-000' + (orderId || 'N/A'), 15, detailsY + 8);

            pdf.setFont('helvetica', 'normal');
            pdf.setFontSize(10);
            let lineY = detailsY + 16;

            if (item.sizeLabel) {
                pdf.setFont('helvetica', 'bold');
                pdf.text('Size:', 15, lineY);
                pdf.setFont('helvetica', 'normal');
                pdf.text(item.sizeLabel, 45, lineY);
                lineY += 7;
            }

            if (item.flowerQuantities && Object.keys(item.flowerQuantities).length > 0) {
                pdf.setFont('helvetica', 'bold');
                pdf.text('Flowers:', 15, lineY);
                pdf.setFont('helvetica', 'normal');
                lineY += 6;
                Object.entries(item.flowerQuantities).forEach(([flower, qty]) => {
                    pdf.text(`  • ${flower} : ${qty}`, 15, lineY);
                    lineY += 6;
                });
            }

            // --- Footer ---
            pdf.setFontSize(8);
            pdf.setTextColor(160, 160, 160);
            pdf.text('Generated by RedshanFlora Employee Portal', 15, 287);

            pdf.save(`bouquet-order-${orderId}.pdf`);
        };

        img.onerror = () => {
            alert('Failed to load bouquet image for PDF export.');
        };
    };

    //------------------ STATE ------------------------------------------------------
    const [rowStatuses, setRowStatuses] = useState({});
    const [expandedOrders, setExpandedOrders] = useState({});

    //------------------ NORMALIZE STATUS -------------------------------------------
    const normalizeStatus = (status) => {
        if (!status) {
            return 'PENDING';
        }
        const value = String(status).toUpperCase();
        switch (value) {
            case 'START':
            case 'IN PROGRESS':
            case 'PROCESSING':
                return 'START';
            case 'STOP':
            case 'STOPPED':
                return 'STOP';
            case 'COMPLETED':
                return 'COMPLETED';
            case 'PENDING':
            default:
                return 'PENDING';
        }
    };

    //------------------ INITIALIZE STATUSES FROM BACKEND ---------------------------
    useEffect(() => {
        const newStatuses = {};
        displayOrders.forEach((order) => {
            const items = Array.isArray(order.items) ? order.items : [];
            items.forEach((item) => {
                const rowKey = `${order.orderId}-${item.itemId}`;
                newStatuses[rowKey] = normalizeStatus(item.status);
            });
        });
        setRowStatuses(newStatuses);
    }, [orders]);

    //------------------ GROUP ORDERS -----------------------------------------------
    const groupedOrders = useMemo(() => {
        return displayOrders.map((order) => {
            return {
                orderId: order.orderId,
                numberOfItems: order.numberOfItems ?? 0,
                totalQuantity: order.totalQuantity ?? 0,
                items: Array.isArray(order.items) ? order.items : []
            };
        });
    }, [displayOrders]);

    //------------------ TOGGLE ORDER EXPAND / COLLAPSE -----------------------------
    const toggleExpand = (orderId) => {
        setExpandedOrders((previous) => ({
            ...previous,
            [orderId]: !previous[orderId]
        }));
    };

    //------------------ START ITEM -------------------------------------------------
    const handleStart = async (rowKey, orderId, itemId) => {
        try {
            const result = onStart ? await onStart(orderId, itemId) : true;
            if (result === false) {
                return;
            }

            setRowStatuses((previous) => ({
                ...previous,
                [rowKey]: 'START'
            }));
        } catch (error) {
            // Handled in parent
        }
    };

    //------------------ STOP ITEM --------------------------------------------------
    const handleStop = async (rowKey, orderId, itemId) => {
        try {
            const result = onStop ? await onStop(orderId, itemId) : true;
            if (result === false) {
                return;
            }

            setRowStatuses((previous) => ({
                ...previous,
                [rowKey]: 'STOP'
            }));
        } catch (error) {
            // Handled in parent
        }
    };

    //------------------ RESUME ITEM ------------------------------------------------
    const handleResume = async (rowKey, orderId, itemId) => {
        try {
            const action = onResume || onStart;
            const result = action ? await action(orderId, itemId) : true;
            if (result === false) {
                return;
            }

            setRowStatuses((previous) => ({
                ...previous,
                [rowKey]: 'START'
            }));
        } catch (error) {
            // Handled in parent
        }
    };

    //------------------ COMPLETE ITEM ----------------------------------------------
    const handleComplete = async (rowKey, orderId, itemId) => {
        try {
            const result = onComplete ? await onComplete(orderId, itemId) : true;
            if (result === false) {
                return;
            }

            setRowStatuses((previous) => ({
                ...previous,
                [rowKey]: 'COMPLETED'
            }));
        } catch (error) {
            // Handled in parent
        }
    };

    //------------------ STATUS BADGE -----------------------------------------------
    const renderStatusBadge = (status) => {
        const normalizedStatus = normalizeStatus(status);

        switch (normalizedStatus) {
            case 'START':
                return (
                    <span className="status-badge status-badge-progress">
                        <Play size={10} fill="currentColor" />
                        In Progress
                    </span>
                );

            case 'STOP':
                return (
                    <span className="status-badge status-badge-stopped">
                        <Pause size={10} fill="currentColor" />
                        Stopped
                    </span>
                );

            case 'COMPLETED':
                return (
                    <span className="status-badge status-badge-completed">
                        <Check size={10} />
                        Completed
                    </span>
                );

            case 'PENDING':
            default:
                return (
                    <span className="status-badge status-badge-pending">
                        <AlertCircle size={10} />
                        Pending
                    </span>
                );
        }
    };

    //------------------ EMPTY STATE ------------------------------------------------
    if (groupedOrders.length === 0) {
        return (
            <div className="employee-empty-state">
                <div className="employee-empty-icon-wrapper">
                    <Inbox size={32} />
                </div>
                <h3 className="employee-empty-title">
                    No assigned works
                </h3>
                <p className="employee-empty-text">
                    You currently have no customized orders assigned. Check back later!
                </p>
            </div>
        );
    }

    //------------------ MAIN TABLE -------------------------------------------------
    return (
        <div className="employee-table-container">
            <table className="employee-table">
                <thead>
                    <tr>
                        <th>Order ID</th>
                        <th>Number of Items</th>
                        <th style={{ textAlign: 'right', paddingRight: '40px' }}>
                            Items Details
                        </th>
                    </tr>
                </thead>

                <tbody>
                    {groupedOrders.map((group) => {
                        const isExpanded = !!expandedOrders[group.orderId];

                        return (
                            <React.Fragment key={group.orderId}>
                                <tr>
                                    <td style={{ fontWeight: '700', color: 'var(--color-primary, #744F51)' }}>
                                        {group.orderId ? `#RS-000${group.orderId}` : "-"}
                                    </td>

                                    <td style={{ fontWeight: '600' }}>
                                        {group.numberOfItems}{' '}
                                        {group.numberOfItems === 1 ? 'Item' : 'Items'}
                                    </td>

                                    <td style={{ textAlign: 'right', paddingRight: '20px' }}>
                                        <button
                                            type="button"
                                            className="expand-btn"
                                            onClick={() => toggleExpand(group.orderId)}
                                        >
                                            {isExpanded ? (
                                                <>
                                                    Hide Items
                                                    <ChevronUp size={16} />
                                                </>
                                            ) : (
                                                <>
                                                    Show Items
                                                    <ChevronDown size={16} />
                                                </>
                                            )}
                                        </button>
                                    </td>
                                </tr>

                                {isExpanded && (
                                    <tr>
                                        <td
                                            colSpan={3}
                                            style={{ padding: 0, backgroundColor: 'var(--color-bg-page)' }}
                                        >
                                            <div className="expanded-row-container">
                                                <table className="employee-sub-table">
                                                    <thead>
                                                        <tr>
                                                            <th>Custom ID</th>
                                                            <th>Item Name</th>
                                                            <th>Flowers &amp; Quantities</th>
                                                            <th>Bouquet Image</th>
                                                            <th>Status</th>
                                                            <th>Actions</th>
                                                        </tr>
                                                    </thead>

                                                    <tbody>
                                                        {group.items.length === 0 ? (
                                                            <tr>
                                                                <td
                                                                    colSpan={6}
                                                                    style={{ textAlign: 'center', padding: '20px' }}
                                                                >
                                                                    No customized item details available.
                                                                </td>
                                                            </tr>
                                                        ) : (
                                                            group.items.map((item) => {
                                                                const customId = item.itemId;
                                                                const rowKey = `${group.orderId}-${customId}`;
                                                                const status =
                                                                    rowStatuses[rowKey] ||
                                                                    normalizeStatus(item.status);

                                                                return (
                                                                    <tr key={rowKey}>
                                                                        <td>
                                                                            <span
                                                                                className="item-id-clickable"
                                                                                onClick={() =>
                                                                                    onItemClick &&
                                                                                    onItemClick({
                                                                                        ...item,
                                                                                        orderId: group.orderId,
                                                                                        itemId: customId
                                                                                    })
                                                                                }
                                                                            >
                                                                                {customId}
                                                                            </span>
                                                                        </td>

                                                                        <td style={{ fontWeight: '600' }}>
                                                                            {item.itemName || 'Customized Bouquet'}
                                                                        </td>

                                                                        {/* Flower Type and Quantity displayed line by line */}
                                                                        <td>
                                                                            {item.flowerQuantities && Object.keys(item.flowerQuantities).length > 0 ? (
                                                                                <div style={{ display: 'flex', flexDirection: 'column', gap: '4px' }}>
                                                                                    {Object.entries(item.flowerQuantities).map(([flowerName, qty]) => (
                                                                                        <span key={flowerName} style={{ fontSize: '13px', lineHeight: '1.4' }}>
                                                                                            <span style={{ fontWeight: '600' }}>{flowerName}</span> : {qty}
                                                                                        </span>
                                                                                    ))}
                                                                                </div>
                                                                            ) : (
                                                                                <span style={{ color: '#888' }}>-</span>
                                                                            )}
                                                                        </td>

                                                                        {/* Bouquet Image column */}
                                                                        <td>
                                                                            {item.imageUrl ? (
                                                                                <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: '6px' }}>
                                                                                    <img
                                                                                        src={`http://localhost:8080${item.imageUrl}`}
                                                                                        alt="Bouquet"
                                                                                        style={{
                                                                                            width: '64px',
                                                                                            height: '64px',
                                                                                            objectFit: 'cover',
                                                                                            borderRadius: '8px',
                                                                                            border: '1.5px solid #e5d8d8',
                                                                                            cursor: 'pointer'
                                                                                        }}
                                                                                        onClick={() => window.open(`http://localhost:8080${item.imageUrl}`, '_blank')}
                                                                                    />
                                                                                    <button
                                                                                        onClick={() => handleExportPdf(item, group.orderId)}
                                                                                    >
                                                                                        ⬇ Export PDF
                                                                                    </button>
                                                                                </div>
                                                                            ) : (
                                                                                <span style={{ color: '#aaa', fontSize: '13px' }}>—</span>
                                                                            )}
                                                                        </td>

                                                                        <td>
                                                                            {renderStatusBadge(status)}
                                                                        </td>

                                                                        <td>
                                                                            <div className="employee-table-actions-cell">
                                                                                {status === 'PENDING' && (
                                                                                    <EStartButton
                                                                                        onClick={() =>
                                                                                            handleStart(rowKey, group.orderId, customId)
                                                                                        }
                                                                                        label="Start"
                                                                                    />
                                                                                )}

                                                                                {status === 'START' && (
                                                                                    <>
                                                                                        <EStopButton
                                                                                            onClick={() =>
                                                                                                handleStop(rowKey, group.orderId, customId)
                                                                                            }
                                                                                            label="Stop"
                                                                                        />
                                                                                        <ECompletedButton
                                                                                            onClick={() =>
                                                                                                handleComplete(rowKey, group.orderId, customId)
                                                                                            }
                                                                                            label="Complete"
                                                                                        />
                                                                                    </>
                                                                                )}

                                                                                {status === 'STOP' && (
                                                                                    <>
                                                                                        <EStartButton
                                                                                            onClick={() =>
                                                                                                handleResume(rowKey, group.orderId, customId)
                                                                                            }
                                                                                            label="Resume"
                                                                                        />
                                                                                        <ECompletedButton
                                                                                            onClick={() =>
                                                                                                handleComplete(rowKey, group.orderId, customId)
                                                                                            }
                                                                                            label="Complete"
                                                                                        />
                                                                                    </>
                                                                                )}

                                                                                {status === 'COMPLETED' && (
                                                                                    <span
                                                                                        style={{
                                                                                            color: '#0f766e',
                                                                                            fontWeight: '700',
                                                                                            fontSize: '12.5px',
                                                                                            display: 'inline-flex',
                                                                                            alignItems: 'center',
                                                                                            gap: '4px'
                                                                                        }}
                                                                                    >
                                                                                        <Check size={14} />
                                                                                        Completed
                                                                                    </span>
                                                                                )}
                                                                            </div>
                                                                        </td>
                                                                    </tr>
                                                                );
                                                            })
                                                        )}
                                                    </tbody>
                                                </table>
                                            </div>
                                        </td>
                                    </tr>
                                )}
                            </React.Fragment>
                        );
                    })}
                </tbody>
            </table>
        </div>
    );
}